def run():
    # 1) 更新 JSON
    with open(KB_PATH, encoding="utf-8") as f:
        kb = json.load(f)
    existing_ids = {k["id"] for k in kb}
    added = 0
    for entry in NEW_ENTRIES:
        eid, cat, q, a, kws = entry
        if eid in existing_ids:
            continue
        kb.append({"id": eid, "category": cat, "question": q, "answer": a, "keywords": kws})
        existing_ids.add(eid)
        added += 1
    with open(KB_PATH, "w", encoding="utf-8") as f:
        json.dump(kb, f, ensure_ascii=False, indent=2)
    print(f"JSON 追加 {added} 条，现有 {len(kb)} 条")

    # 2) 同步 Neo4j CartographyRule
    with driver.session() as s:
        n = 0
        for entry in NEW_ENTRIES:
            eid, cat, q, a, kws = entry
            s.run(
                "MERGE (n:CartographyRule {name:$name}) SET n += $props",
                name=eid, props={"question": q, "answer": a, "category": cat, "source": "kb-rag2", "keywords": json.dumps(kws, ensure_ascii=False)},
            )
            # 关联到 MapType/MapElement/MapSymbol/ScaleRule/DataRule 等标签节点
            for rel_to in ("MapType", "MapElement", "MapSymbol", "ScaleRule", "DataRule", "EditRule", "LegendRule", "MapProjection", "GeneralizationRule", "ColorSchemeRule"):
                s.run(
                    "MATCH (a:CartographyRule {name:$aname}) MATCH (b) "
                    "WHERE any(l IN labels(b) WHERE l=$blabel) "
                    "WITH a, b LIMIT 2 MERGE (a)-[r:RELATES_TO]->(b) SET r.source='kb-rag2'",
                    aname=eid, blabel=rel_to,
                )
            n += 1
        nodes = s.run("MATCH (n) RETURN count(n) AS c").single()["c"]
        rels = s.run("MATCH ()-[r]->() RETURN count(r) AS c").single()["c"]
        rules = s.run("MATCH (n) WHERE n.question IS NOT NULL RETURN count(n) AS c").single()["c"]
        print(f"Neo4j 同步 {n} 条")
        print(f"图谱总计: nodes={nodes} relations={rels} 知识规则节点={rules}")
    driver.close()

run()
